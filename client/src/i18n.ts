const dicts: Record<Lang, Dict> = { en, ar };
type ListKey = 'rulesList' | 'rulesListTawla' | 'rulesListChess' | 'rulesListLudo';
export type Key = Exclude<keyof Dict, ListKey>;

let lang: Lang = 'ar';
export const getLang = () => lang;
export const setLang = (l: Lang) => {
  lang = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
};
export const num = (n: number) => new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US').format(n);
export function t(k: Key, p: Record<string, string | number> = {}): string {
  let s = (dicts[lang][k] ?? en[k] ?? k) as string;
  for (const [key, v] of Object.entries(p)) s = s.split(`{${key}}`).join(typeof v === 'number' ? num(v) : v);
  return s;
}
